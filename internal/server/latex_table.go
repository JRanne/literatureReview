package server

import (
	"fmt"
	"net/http"
	"strings"

	"literaturereview/internal/model"
)

// latexCols are the columns available for the LaTeX summary table, keyed by
// the short name used in ?cols=. Width is a share of \textwidth.
var latexCols = []struct {
	Key, Header string
	Width       float64
	Get         func(*model.Paper) string
}{
	{"study", "Study", 0.14, func(p *model.Paper) string { return `\citet{` + p.BibKey + `}` }},
	{"year", "Year", 0.05, func(p *model.Paper) string { return yearStr(p.Year) }},
	{"venue", "Venue", 0.14, func(p *model.Paper) string { return p.Venue }},
	{"tier", "Venue tier", 0.07, venueTier},
	{"objective", "Objective", 0.22, func(p *model.Paper) string { return ex(p).Objective }},
	{"method", "Method", 0.16, func(p *model.Paper) string { return ex(p).Method }},
	{"context", "Context", 0.14, func(p *model.Paper) string { return ex(p).Context }},
	{"findings", "Key findings", 0.26, func(p *model.Paper) string { return ex(p).Findings }},
	{"theory", "Theory", 0.12, func(p *model.Paper) string { return ex(p).Theory }},
	{"contribution", "Contribution", 0.18, func(p *model.Paper) string { return ex(p).Contribution }},
	{"limitations", "Limitations", 0.16, func(p *model.Paper) string { return ex(p).Limitations }},
	{"relevance", "Relevance to RQ", 0.18, func(p *model.Paper) string { return ex(p).Relevance }},
	{"keywords", "Keywords", 0.14, func(p *model.Paper) string { return strings.Join(ex(p).Keywords, ", ") }},
	{"score", "Screening", 0.07, func(p *model.Paper) string { return fmt.Sprint(p.RankScore()) }},
}

const defaultLatexCols = "study,method,context,findings,theory"

func ex(p *model.Paper) model.Extraction {
	if p.Extract == nil {
		return model.Extraction{}
	}
	return *p.Extract
}

// handleTableLaTeX renders the included papers as a longtable.
func (s *Server) handleTableLaTeX(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	want := strings.Split(strings.TrimSpace(r.URL.Query().Get("cols")), ",")
	if want[0] == "" {
		want = strings.Split(defaultLatexCols, ",")
	}
	var cols []int
	for _, k := range want {
		for i, c := range latexCols {
			if c.Key == strings.TrimSpace(k) {
				cols = append(cols, i)
			}
		}
	}
	if len(cols) == 0 {
		http.Error(w, "no valid columns; choose from: "+latexColKeys(), 400)
		return
	}
	var papers []*model.Paper
	var title string
	if err := s.store.Update(id, func(p *model.Project) error {
		p.EnsureBibKeys()
		title = p.Title
		for _, pp := range p.Kept() {
			c := *pp
			papers = append(papers, &c)
		}
		return nil
	}); err != nil {
		http.NotFound(w, r)
		return
	}
	total := 0.0
	for _, i := range cols {
		total += latexCols[i].Width
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "%% Summary of included studies — %s\n%% Generated by litreview. Requires \\usepackage{longtable,booktabs,array} and a citation package\n%% (natbib or biblatex with natbib=true); cite keys match bibliography.bib.\n", latexEscape(title))
	sb.WriteString("% Columns: " + strings.Join(want, ", ") + " — choose others with ?cols= from: " + latexColKeys() + "\n\n")
	sb.WriteString(`\begin{longtable}{`)
	for _, i := range cols {
		fmt.Fprintf(&sb, ">{\\raggedright\\arraybackslash}p{%.2f\\textwidth}", latexCols[i].Width/total*0.96)
	}
	sb.WriteString("}\n")
	fmt.Fprintf(&sb, "\\caption{Included studies (n = %d).}\\label{tab:included-studies}\\\\\n\\toprule\n", len(papers))
	var hdr []string
	for _, i := range cols {
		hdr = append(hdr, `\textbf{`+latexEscape(latexCols[i].Header)+`}`)
	}
	sb.WriteString(strings.Join(hdr, " & ") + " \\\\\n\\midrule\n\\endfirsthead\n")
	fmt.Fprintf(&sb, "\\multicolumn{%d}{l}{\\textit{Table \\ref{tab:included-studies} continued}}\\\\\n\\toprule\n%s \\\\\n\\midrule\n\\endhead\n\\midrule\n\\multicolumn{%d}{r}{\\textit{continued on next page}}\\\\\n\\endfoot\n\\bottomrule\n\\endlastfoot\n", len(cols), strings.Join(hdr, " & "), len(cols))
	for _, p := range papers {
		var cells []string
		for _, i := range cols {
			v := latexCols[i].Get(p)
			if latexCols[i].Key == "study" {
				cells = append(cells, v) // already a \citet command
			} else {
				cells = append(cells, latexEscape(v))
			}
		}
		sb.WriteString(strings.Join(cells, " & ") + " \\\\\n")
	}
	sb.WriteString("\\end{longtable}\n")
	w.Header().Set("Content-Type", "application/x-tex; charset=utf-8")
	w.Header().Set("Content-Disposition", `attachment; filename="included-studies.tex"`)
	_, _ = w.Write([]byte(sb.String()))
}

func latexColKeys() string {
	var ks []string
	for _, c := range latexCols {
		ks = append(ks, c.Key)
	}
	return strings.Join(ks, ", ")
}

// handleConceptsLaTeX renders the concept matrix with rotated headers.
func (s *Server) handleConceptsLaTeX(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	var papers []*model.Paper
	var concepts []model.Concept
	var title string
	if err := s.store.Update(id, func(p *model.Project) error {
		p.EnsureBibKeys()
		title = p.Title
		concepts = p.Concepts
		for _, pp := range p.Kept() {
			c := *pp
			papers = append(papers, &c)
		}
		return nil
	}); err != nil {
		http.NotFound(w, r)
		return
	}
	if len(concepts) == 0 {
		http.Error(w, "no concept matrix yet; build it first", 400)
		return
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "%% Concept matrix — %s\n%% Generated by litreview. Requires \\usepackage{longtable,booktabs,graphicx,amssymb} and natbib/biblatex; cite keys match bibliography.bib.\n\n", latexEscape(title))
	fmt.Fprintf(&sb, "\\begin{longtable}{l*{%d}{c}}\n\\caption{Concept matrix of the included studies (n = %d).}\\label{tab:concept-matrix}\\\\\n\\toprule\n", len(concepts), len(papers))
	var hdr []string
	for _, c := range concepts {
		hdr = append(hdr, `\rotatebox{90}{\textbf{`+latexEscape(c.Name)+`}}`)
	}
	head := `\textbf{Study} & ` + strings.Join(hdr, " & ") + " \\\\\n\\midrule\n"
	sb.WriteString(head + "\\endfirsthead\n\\toprule\n" + head + "\\endhead\n\\bottomrule\n\\endlastfoot\n")
	for _, p := range papers {
		hit := map[string]bool{}
		for _, h := range p.Concepts {
			hit[h.Name] = true
		}
		var cells []string
		for _, c := range concepts {
			if hit[c.Name] {
				cells = append(cells, `$\bullet$`)
			} else {
				cells = append(cells, "")
			}
		}
		sb.WriteString(`\citet{` + p.BibKey + "} & " + strings.Join(cells, " & ") + " \\\\\n")
	}
	sb.WriteString("\\end{longtable}\n")
	w.Header().Set("Content-Type", "application/x-tex; charset=utf-8")
	w.Header().Set("Content-Disposition", `attachment; filename="concept-matrix.tex"`)
	_, _ = w.Write([]byte(sb.String()))
}
